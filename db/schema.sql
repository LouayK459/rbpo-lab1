BEGIN;

CREATE TABLE delivery.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT users_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE delivery.shipments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL,
    address VARCHAR(255) NOT NULL,
    weight NUMERIC(12, 3) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'CREATED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delivered_at TIMESTAMPTZ,
    CONSTRAINT shipments_sender_fk FOREIGN KEY (sender_id)
        REFERENCES delivery.users(id) ON DELETE RESTRICT,
    CONSTRAINT shipments_address_not_blank CHECK (btrim(address) <> ''),
    CONSTRAINT shipments_weight_positive CHECK (weight > 0 AND weight < 1000000000),
    CONSTRAINT shipments_status_valid
        CHECK (status IN ('CREATED', 'IN_TRANSIT', 'DELIVERED')),
    CONSTRAINT shipments_delivery_time_valid
        CHECK ((status = 'DELIVERED') = (delivered_at IS NOT NULL)),
    CONSTRAINT shipments_delivery_after_creation
        CHECK (delivered_at IS NULL OR delivered_at >= created_at)
);

CREATE INDEX shipments_sender_idx ON delivery.shipments(sender_id);

CREATE TABLE delivery.routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_date DATE NOT NULL,
    max_weight NUMERIC(12, 3) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PLANNED',
    CONSTRAINT routes_max_weight_positive
        CHECK (max_weight > 0 AND max_weight < 1000000000),
    CONSTRAINT routes_status_valid
        CHECK (status IN ('PLANNED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE delivery.stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL,
    address VARCHAR(255) NOT NULL,
    sequence_number INTEGER NOT NULL,
    CONSTRAINT stops_route_fk FOREIGN KEY (route_id)
        REFERENCES delivery.routes(id) ON DELETE RESTRICT,
    CONSTRAINT stops_address_not_blank CHECK (btrim(address) <> ''),
    CONSTRAINT stops_sequence_positive CHECK (sequence_number > 0),
    CONSTRAINT stops_route_sequence_unique UNIQUE (route_id, sequence_number)
);

CREATE TABLE delivery.shipment_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL,
    stop_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ASSIGNED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    CONSTRAINT assignments_shipment_fk FOREIGN KEY (shipment_id)
        REFERENCES delivery.shipments(id) ON DELETE RESTRICT,
    CONSTRAINT assignments_stop_fk FOREIGN KEY (stop_id)
        REFERENCES delivery.stops(id) ON DELETE RESTRICT,
    CONSTRAINT assignments_status_valid
        CHECK (status IN ('ASSIGNED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT assignments_completion_time_valid
        CHECK ((status = 'COMPLETED') = (completed_at IS NOT NULL)),
    CONSTRAINT assignments_completion_after_creation
        CHECK (completed_at IS NULL OR completed_at >= created_at)
);

CREATE UNIQUE INDEX assignments_active_shipment_unique
    ON delivery.shipment_assignments(shipment_id)
    WHERE status IN ('ASSIGNED', 'IN_PROGRESS');

CREATE INDEX assignments_stop_idx ON delivery.shipment_assignments(stop_id);

COMMIT;
